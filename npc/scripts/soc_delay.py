#!/usr/bin/env python3
"""Build a simulation-only instrumented wrapper from the real CPU wrapper.

Keep its module/instance hierarchy for the existing monitor, changing only
the external AXI connections. Never edit the maintained RTL or generated SoC.
The separate filelist makes the extra registers impossible to enter DC/PT via
filelist-soc.f. Refuse an unexpected port shape instead of silently dropping it.
"""
import argparse
from pathlib import Path
import re

NPC = Path(__file__).resolve().parents[1]


def generate(out):
    source = NPC / 'vsrc/top/ysyx_25030087.sv'
    text = source.read_text()
    header = text.split(');', 1)[0]
    ports = {name: (direction, int(width) + 1 if width else 1)
             for direction, width, name in re.findall(
                 r'\b(input|output)\s+(?:\[(\d+):0\]\s+)?(io_master_\w+)', header)}
    channels = [('ar', ['id', 'addr', 'len', 'size', 'burst']),
                ('aw', ['id', 'addr', 'len', 'size', 'burst']),
                ('w', ['data', 'strb', 'last']),
                ('r', ['id', 'data', 'resp', 'last']), ('b', ['id', 'resp'])]
    expected = {f'io_master_{ch}{field}' for ch, fields in channels
                for field in ['valid', 'ready', *fields]}
    assert set(ports) == expected, 'CPU AXI shape changed; review the interposer'
    declarations = []
    for name, (_, width) in ports.items():
        declarations.append(f'wire [{width-1}:0] raw_{name};')
        text, n = re.subn(r'(\.m_axi_\w+\()' + name + r'(\))',
                          r'\1raw_' + name + r'\2', text)
        assert n == 1, (name, n)
    instances = []
    for index, (ch, fields) in enumerate(channels):
        upstream, downstream = ('raw_', '') if ch in ('ar', 'aw', 'w') else ('', 'raw_')
        prefix = f'io_master_{ch}'
        width = sum(ports[prefix + field][1] for field in fields)
        def packed(side):
            return '{' + ','.join(side + prefix + field for field in fields) + '}'
        instances.append(f'''npc_soc_delay_channel #(.WIDTH({width}), .CHANNEL({index})) delay_{ch} (
    .clock(clock), .reset(reset),
    .s_valid({upstream}{prefix}valid), .s_ready({upstream}{prefix}ready), .s_data({packed(upstream)}),
    .m_valid({downstream}{prefix}valid), .m_ready({downstream}{prefix}ready), .m_data({packed(downstream)})
);''')
    text = text.replace('ysyx_soc_cpu #', '\n'.join(declarations) + '\nysyx_soc_cpu #', 1)
    assert text.count('endmodule') == 1
    text = text.replace('endmodule', '\n'.join(instances) + '\nendmodule')
    out.mkdir(parents=True, exist_ok=True)
    wrapper = out / 'ysyx_25030087_delay.sv'
    wrapper.write_text('// Generated by npc/scripts/soc_delay.py; simulation only.\n' + text)
    paths = [(NPC / line.strip()).resolve() for line in (NPC / 'filelist-soc.f').read_text().splitlines() if line.strip()]
    assert paths.count(source) == 1
    (out / 'filelist-delay.f').write_text('\n'.join(str(wrapper if p == source else p) for p in paths)
                                        + '\n' + str(NPC / 'sim/soc_delay_channel.sv') + '\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out', type=Path, required=True)
    generate(p.parse_args().out.resolve())
